#!/usr/bin/env python3
"""Writes Silverpoint's launcher icon (adaptive icon layers and the themed monochrome layer).

The mark is silver-halide grains on a golden-angle spiral, converging on one bright point. The same
geometry is drawn by the app (ui/SilverpointMark.kt) and by the start-up animation
(motion/src/Mark.ts): grain i (from 1) sits at radius 3*sqrt(i) and angle i * 137.508 degrees,
in a 108-unit box, until the radius passes 38.

    python3 scripts/make_logo.py
"""
import math
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")
GOLDEN = math.radians(137.508)
R_MAX = 38.0


def grains():
    """(x, y, radius, alpha) for every grain, in mark units centred on 0."""
    out = []
    i = 1
    while True:
        rr = 3.0 * math.sqrt(i)
        if rr > R_MAX:
            return out
        out.append((rr * math.cos(i * GOLDEN), rr * math.sin(i * GOLDEN), 0.35 + rr / R_MAX * 1.25, 0.35 + 0.65 * (1 - rr / 40)))
        i += 1


def circle(cx, cy, r):
    return f"M{cx - r:.1f},{cy:.1f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0"


def foreground(scale, mono):
    """The mark at [scale] (1 = 38 units of radius) on a 108 canvas; grains grouped by alpha."""
    c = 54.0
    buckets = {}
    for x, y, r, a in grains():
        key = 1.0 if mono else round(a * 8) / 8
        buckets.setdefault(key, []).append(circle(c + x * scale, c + y * scale, r * scale))
    # Short paths (a few grains each): Android draws long vector paths slowly (lint: VectorPath).
    paths = "\n".join(
        f'    <path android:fillColor="{"#FFFFFFFF" if mono else "#FFD9DDE3"}" android:fillAlpha="{a:.3f}" android:pathData="{"".join(p[k:k + 12])}" />'
        for a, p in sorted(buckets.items())
        for k in range(0, len(p), 12)
    )
    glow = "" if mono else f"""
    <path android:pathData="{circle(c, c, 11 * scale)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{c}" android:centerY="{c}" android:gradientRadius="{11 * scale:.2f}">
                <item android:offset="0" android:color="#FFFFFFFF" />
                <item android:offset="0.25" android:color="#D9E8EEF6" />
                <item android:offset="1" android:color="#009FB3C8" />
            </gradient>
        </aapt:attr>
    </path>"""
    point = f'    <path android:fillColor="#FFFFFFFF" android:pathData="{circle(c, c, (4 if mono else 3.2) * scale)}" />'
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_logo.py: Silverpoint's mark, silver grains spiralling into one point of light. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{paths}{glow}
{point}
</vector>
"""


BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_logo.py: graphite, lighter at the top left. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF2B3038" />
                <item android:offset="1" android:color="#FF0B0D10" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""

def svg_icon():
    """The launcher icon as an SVG (graphite squircle-ish square, the mark), for the README and stores."""
    s = 0.74
    dots = "".join(
        f'<circle cx="{54 + x * s:.2f}" cy="{54 + y * s:.2f}" r="{r * s:.2f}" fill="#d9dde3" fill-opacity="{a:.3f}"/>' for x, y, r, a in grains()
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">
<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#2b3038"/><stop offset="1" stop-color="#0b0d10"/></linearGradient>
<radialGradient id="glow"><stop offset="0" stop-color="#fff"/><stop offset=".25" stop-color="#e8eef6" stop-opacity=".85"/><stop offset="1" stop-color="#9fb3c8" stop-opacity="0"/></radialGradient></defs>
<rect width="108" height="108" rx="26" fill="url(#bg)"/>{dots}<circle cx="54" cy="54" r="{11 * s:.2f}" fill="url(#glow)"/><circle cx="54" cy="54" r="{3.2 * s:.2f}" fill="#fff"/></svg>
"""


if __name__ == "__main__":
    # The launcher masks keep the middle 72 of 108 units (66 for a circle): the mark is scaled to fit.
    files = {
        "ic_launcher_background.xml": BACKGROUND,
        "ic_launcher_foreground.xml": foreground(0.74, mono=False),
        "ic_launcher_monochrome.xml": foreground(0.74, mono=True),
    }
    for name, text in files.items():
        with open(os.path.join(ROOT, name), "w") as f:
            f.write(text)
    brand = os.path.join(os.path.dirname(__file__), "..", "docs", "brand")
    os.makedirs(brand, exist_ok=True)
    with open(os.path.join(brand, "icon.svg"), "w") as f:
        f.write(svg_icon())
    print(f"{len(grains())} grains; wrote", ", ".join(files), "and docs/brand/icon.svg")
